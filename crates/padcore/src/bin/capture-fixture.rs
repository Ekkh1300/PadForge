//! Reads one real DS4 report and writes it as a Rust fixture, so the test data
//! comes from the device rather than from anyone transcribing hex by hand.
//!
//! A fixture typed by hand is a fixture that can be wrong in a way the test then
//! enshrines. Three bugs survived here for exactly that reason: the tests were
//! built from an assumption about the report layout, the assumption was wrong,
//! and the tests confirmed it. Generating this from the pad removes the step
//! where a belief becomes data.
//!
//! Run:
//!     cargo run -p padcore --bin capture-fixture --release --target x86_64-pc-windows-gnu

use std::fmt::Write as _;

use padcore::device::probe_matching_devices;

/// Reports to read before saving. The pad resends its state constantly, so a
/// handful of frames differ only in the timestamp; one is enough and the point
/// is to record the layout, not a particular frame.
const READS: usize = 12;

fn main() {
    let devices = probe_matching_devices();
    if devices.is_empty() {
        eprintln!("no DS4 is connected, so there is nothing to capture");
        std::process::exit(1);
    }

    let api = match hidapi::HidApi::new() {
        Ok(a) => a,
        Err(e) => {
            eprintln!("could not initialise the HID API: {e}");
            std::process::exit(1);
        }
    };

    for info in &devices {
        let Ok(path) = std::ffi::CString::new(info.path.as_str()) else {
            continue;
        };
        let Ok(device) = api.open_path(&path) else {
            continue;
        };

        let mut buffer = [0u8; 256];
        for _ in 0..READS {
            if let Ok(n) = device.read_timeout(&mut buffer, 50) {
                if n == 0 {
                    continue;
                }
                let frame = &buffer[..n];

                // Trim the tail Windows pads the read with. Trailing zeros are
                // not information: every field in this report is a value, and a
                // run of them at the end is padding rather than payload.
                let mut end = frame.len();
                while end > 1 && frame[end - 1] == 0 {
                    end -= 1;
                }
                // The CRC sits at the very end and is non-zero, so trimming stops
                // there naturally. Report what was kept rather than the read
                // length, since only the former belongs in a test.
                println!(
                    "read {} bytes, kept {} (bus {}, pid {:04x})",
                    n, end, info.bus_type, info.product_id
                );

                let mut out = String::new();
                for (i, b) in frame[..end].iter().enumerate() {
                    if i % 14 == 0 {
                        out.push_str("\n            ");
                    }
                    let _ = write!(out, "0x{b:02x}, ");
                }

                let body = format!(
                    "/// Verbatim {}-byte frame from a DS4 (bus {}, PID {:#06x}), trimmed of\n    /// the trailing padding Windows adds to a HID read.\n    ///\n    /// Generated by `cargo run -p padcore --bin capture-fixture`. Not typed by hand:\n    /// the whole point is that the bytes come from the device rather than from an\n    /// assumption about what the device sends.\n    pub(crate) const {}_REPORT: [u8; {}] = [{}];",
                    end, info.bus_type, info.product_id, info.product_id, end, out
                );

                let path = std::path::Path::new("target").join("captured-report.txt");
                std::fs::write(&path, &body).expect("could not write the fixture");
                println!("wrote {}", path.display());
                return;
            }
        }
    }

    eprintln!("could not read a single report from the connected pad");
    std::process::exit(1);
}
